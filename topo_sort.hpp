//==================================================================================================
//  トポロジカルソート（Kahn 法）
//
//  ノード 0..n-1 を、依存先が先に来る順番に並べる。（B が A に依存するなら A → B の順）
//  ノードの種類（モーター、タスクなど）には依存しない。ノードは番号で扱う。
//
//  Graph には、次の2つの関数があればよい。（基底クラスの継承や virtual は要らない）
//    int dep_count(int i) const     : ノード i の依存の本数
//    int dep(int i , int d) const   : ノード i の d 本目の依存先の番号 (0..n-1)。グラフの外なら -1（無視する）
//
//  order[0..n-1] に、ノードの番号を計算する順に並べて返す。
//    成功        : true
//    循環がある  : false。（order は途中まで書き換わっているので使わないこと）
//    n > MaxN    : false。
//
//  やり方
//    1. 各ノードが「あと何本待っているか」(in_degree) を数える。
//    2. 待ちが 0 のノードをキューに入れる。
//    3. キューから1つ出して order に並べ、それを待っていたノードの in_degree を減らす。0 になったらキューに入れる。
//    4. 全部並べられなければ、どこかに循環がある。（循環の中のノードは in_degree が 0 にならない）
//  order の前から順に出すので、order をそのままキューに使う。
//  どのノードもキューに入るのは1回だけなので、キューは n 個で足りる。
//  同じ依存先を2本登録しても、数える時と減らす時で同じ本数を数えるので、正しく並ぶ。
//  計算量はおよそ n^2 × 依存の本数。動的なメモリ確保はしない。
//==================================================================================================
template <int MaxN , class Graph>
bool topo_sort(const Graph& g , int n , int* order) noexcept
{
	if( (n < 0) || (n > MaxN) )	{	return false;	}

	//1. あと何本待っているか
	int in_degree[MaxN] = {};
	for(int i = 0 ; i < n ; ++i){
		for(int d = 0 ; d < g.dep_count(i) ; ++d){
			if(g.dep(i , d) >= 0)	{	++in_degree[i];	}
		}
	}

	//2. 待ちのないノードをキューに入れる
	int head = 0;											//次に出す位置
	int tail = 0;											//次に入れる位置
	for(int i = 0 ; i < n ; ++i){
		if(in_degree[i] == 0)	{	order[tail++] = i;	}
	}

	//3. 1つずつ出して、それを待っていたノードの待ちを減らす
	while(head < tail){
		const int m = order[head++];
		for(int i = 0 ; i < n ; ++i){
			for(int d = 0 ; d < g.dep_count(i) ; ++d){
				if( (g.dep(i , d) == m) && (--in_degree[i] == 0) )	{	order[tail++] = i;	}	//m を待っていた本数だけ減らす
			}
		}
	}

	//4. 全部並べられたか
	return tail == n;
}
